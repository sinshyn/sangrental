import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const require = createRequire(resolve(root, "frontend/package.json"));
const ts = require("typescript");
const { icon } = require("@fortawesome/fontawesome-svg-core");
const { faGauge } = require("@fortawesome/free-solid-svg-icons");
const target = resolve(root, "admin/SangRental.Admin/wwwroot/vendor");
mkdirSync(target, { recursive: true });
const sweet = resolve(root, "frontend/node_modules/sweetalert2");
for (const name of ["sweetalert2.all.min.js", "sweetalert2.min.css"]) copyFileSync(resolve(sweet, "dist", name), resolve(target, name));
copyFileSync(resolve(sweet, "LICENSE"), resolve(target, "SweetAlert2.LICENSE"));
copyFileSync(resolve(root, "frontend/node_modules/@fortawesome/free-solid-svg-icons/LICENSE.txt"), resolve(target, "FontAwesome.LICENSE.txt"));
writeFileSync(resolve(target, "gauge.svg"), icon(faGauge, { attributes: { "aria-hidden": "true" } }).html.join(""));
const source = readFileSync(resolve(root, "frontend/src/lib/notification-core.ts"), "utf8");
writeFileSync(resolve(target, "notification-core.js"), ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText);
copyFileSync(resolve(root, "frontend/src/messages/notifications.json"), resolve(target, "notifications.json"));
copyFileSync(resolve(root, "frontend/src/design/coastal.css"), resolve(target, "coastal.css"));
console.log("Prepared pinned SweetAlert2, shared notification core, six locales and one Font Awesome SVG for admin.");
